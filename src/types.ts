import type {WikiData} from './features/wiki/types';
export type Status = "waiting" | "active" | "done";
export type Bot = {
  cliApplyAll?: boolean;
  cliUsage?: Record<"codex" | "claudeCode" | "other", "active" | "occasional" | "never">;
  id: string;
  name: string;
  role: string;
  avatar: string;
  instructions: string;
  draft: string;
  instructionVersion: number;
  appliedVersion: number;
  appliedAt: string | null;
  appliedSource: string | null;
  lastReportAt: string | null;
  version: number;
};
export type Brief = {
  category?: string;
  title: string;
  description: string;
  criteria: string;
  type: "solo" | "team";
  boss: string;
  members: string[];
  routine: boolean;
  schedule: string;
};
export type FlowNode = {id:string;title:string;description:string;botId:string};
export type FlowEdge = {id:string;source:string;target:string;label?:string};
export type FlowPlan = {version:number;nodes:FlowNode[];edges:FlowEdge[];createdAt:string;createdBy:string};
export type Subtask = {
  nodeId?:string;
  id: string;
  title: string;
  botId: string;
  status: Status;
  progress: number;
  updatedAt: string;
  note?: string;
  blocked?: boolean;
  source?: string;
};
export type Run = {
  flowPlan?:FlowPlan | null;
  brief: Brief;
  id: string;
  instructionVersion: number;
  status: Status;
  progress: number;
  subtasks: Subtask[];
  note: string;
  blocked: boolean;
  createdAt: string;
  updatedAt: string;
  source: string | null;
  reportedBy?: string;
};
export type Task = {
  flowPlan?:FlowPlan | null;
  flowRequestId?:string | null;
  retrospectiveRequestId?: string | null;
  retrospective?: {markdown:string;updatedAt:string;botId:string;requestId:string} | null;
  location?: "active" | "library" | "trash";
  previousLocation?: "active" | "library";
  stage: "brief" | "monitor";
  ready: boolean;
  dispatchId: string | null;
  id: string;
  version: number;
  publishedVersion: number;
  acceptedVersion: number;
  draft: Brief;
  published: Brief | null;
  runs: Run[];
  createdAt: string;
};
export type Event = {
  cancelledAt?: string;
  dispatchId?: string;
  id: string;
  kind: "instruction" | "task" | "retrospective" | "routine" | "flow" | "wiki" | "monitor";
  summary?: string;
  targetId: string;
  version: number;
  message: string;
  recipient: string;
  createdAt: string;
  acknowledgedAt: string | null;
  source: string | null;
};
export type History = {
  id: string;
  action: string;
  targetId: string;
  actor: { kind: string; id: string };
  reason: string;
  at: string;
  snapshot: unknown;
};
export type State = {
  wiki?:WikiData;
  categoryColors?: Record<string, string>;
  activities?: {botId:string; targetId:string; sessionId:string; expiresAt:string}[];
  categories: string[];
  revision: number;
  bots: Bot[];
  tasks: Task[];
  inbox: Event[];
  history: History[];
  csrf: string;
  workspace: string;
  serverTime: string;
};
